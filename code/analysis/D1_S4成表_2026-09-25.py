#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
D1 — 生成补充表 S4（判据敏感性）

稿件 §Supplementary Materials 把 S4 描述为三段，本脚本按同一顺序组装、不重算任何数值：
  S4a 名次随估计量变动      ← 02_结果表/A2_名次随模型变动.csv        （246 行）
  S4b 显著性跨线计数        ← 02_结果表/A2_显著性跨线计数.csv        （  3 行）
  S4c 逐基因留一法重排      ← 02_结果表/A2e_留一法_逐基因名次变动.csv（450 行）

行数口径（2026-09-25 用户裁定）：三段全含；稿件所称的「450 rows」指 S4c 主表，
故稿件 L198 改为「450 rows in the leave-one-cohort-out table」——本脚本按该口径断言。

两条纪律：
  ① **S4 是英文投稿件，不得含汉字。** 源表用中文枚举（发现/复制、交联家族(8)、basis 的中文括注、
     genes 列用「、」分隔），须逐列映射为英文后再落盘；末尾以 assert 断言输出无汉字——
     本项目有过「数值校验全过但上传件带 572 个汉字」的先例。
  ② **映射表须覆盖源表全部取值**。映射写成显式 dict 并断言无遗漏，否则新增取值会被静默原样写出。

输入：02_结果表/{A2_名次随模型变动, A2_显著性跨线计数, A2e_留一法_逐基因名次变动}.csv
输出：06_补充材料/Supplementary_Table_S4.md
"""
import csv
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[3]
REV = ROOT / "08_修订_2026-09-17"
RES = REV / "02_结果表"
OUT = REV / "06_补充材料" / "Supplementary_Table_S4.md"

LAYER = {"发现": "Discovery", "复制": "Replication"}
SET = {"交联家族(8)": "Cross-linking family (8)", "全部基因": "All genes"}
BASIS_RANK = {"abs_logFC": "|log2FC|", "P": "P"}
BASIS_CROSS = {
    "FE_vs_RE（Meta 对，自洽）": "FE vs RE (meta pair, self-consistent)",
    "primary_vs_RE（主估计 vs IVW列的RE）": "Primary vs RE (primary estimate vs RE of the IVW column)",
}
HAN = re.compile(r"[一-鿿　-〿＀-￯]")
# 断言「无汉字」时须放行**路径型 token**：本项目的脚本与目录名本身含中文
# （`03_分析/scripts/D1_S4成表_2026-09-25.py`、`02_结果表/`），把它们当汉字拦下是误报。
# 判据：凡含汉字的空白分隔 token，须是路径/文件名（含 / 或以已知扩展名结尾）；否则即正文汉字。
PATHY = re.compile(r"^[0-9A-Za-z_./一-鿿-]+(?:/|\.(?:py|R|csv|tsv|md|png|pdf))$")


def han_in_prose(text):
    """返回正文里的汉字 token（已放行路径/文件名）。

    先剥掉 token 首尾的标点再判：markdown 里路径总与反引号、逗号、冒号相邻
    （`` `X.R`, ``、`02_结果表/:`），不剥就会把路径误判成正文汉字。
    """
    out = []
    for t in re.findall(r"\S*[一-鿿]\S*", text):
        if not PATHY.match(t.strip("`'\",;:()[]<>*")):
            out.append(t)
    return out


def read(name):
    with open(RES / name, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def must(cond, msg):
    assert cond, msg
    print(f"  OK  {msg}")


def f3(x):
    """logFC：3 位小数（与 S3 的 β 写法一致）。"""
    return "NA" if x in ("NA", "", None) else f"{float(x):+.3f}"


def fp(x):
    """P 值：3 位有效数字。"""
    return "NA" if x in ("NA", "", None) else f"{float(x):.3g}"


def i0(x):
    return "NA" if x in ("NA", "", None) else str(int(float(x)))


def yn(x):
    return "yes" if str(x).strip().upper() == "TRUE" else "no"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


print("D1 生成补充表 S4（判据敏感性）")

# ── 读源表并锁定行数（口径即稿件所称的 450）
a = read("A2_名次随模型变动.csv")
b = read("A2_显著性跨线计数.csv")
c = read("A2e_留一法_逐基因名次变动.csv")
must(len(a) == 246, f"S4a 源表 {len(a)} 行（期望 246）")
must(len(b) == 3, f"S4b 源表 {len(b)} 行（期望 3）")
must(len(c) == 450, f"S4c 源表 {len(c)} 行（期望 450 = 稿件所称的 450 rows）")

# ── 映射表覆盖性（未覆盖的取值会被静默原样写出，故先断言）
must(set(r["layer"] for r in a) <= set(LAYER), "S4a 的 layer 取值已被映射表覆盖")
must(set(r["set"] for r in a) <= set(SET), "S4a 的 set 取值已被映射表覆盖")
must(set(r["basis"] for r in a) <= set(BASIS_RANK), "S4a 的 basis 取值已被映射表覆盖")
must(set(r["layer"] for r in b) <= set(LAYER) and set(r["basis"] for r in b) <= set(BASIS_CROSS),
     "S4b 的 layer/basis 取值已被映射表覆盖")
must(set(r["layer"] for r in c) <= set(LAYER), "S4c 的 layer 取值已被映射表覆盖")

# ── S4a：名次随估计量变动
rows_a = [[LAYER[r["layer"]], SET[r["set"]], BASIS_RANK[r["basis"]], r["gene"],
           i0(r["FE_rank"]), i0(r["RE_rank"]), i0(r["n_in_set"]), i0(r["delta"])] for r in a]

# ── S4b：显著性跨线计数（genes 列的中文顿号改英文逗号）
rows_b = [[LAYER[r["layer"]], BASIS_CROSS[r["basis"]], i0(r["n_eval"]), i0(r["n_crossed"]),
           r["genes"].replace("、", ", "), fp(r["P_min"]), fp(r["P_max"])] for r in b]

# ── S4c：逐基因留一法重排（去掉与 layer+estimator 冗余的 grp 列）
rows_c = [[LAYER[r["layer"]], r["estimator"], r["gene"], r["dropped"], i0(r["k"]),
           f3(r["logFC"]), fp(r["P"]), i0(r["rank_abs_loo"]), i0(r["rank_P_loo"]),
           i0(r["rank_abs_full"]), i0(r["rank_P_full"]), i0(r["d_abs"]), i0(r["d_P"]),
           yn(r["in_panel"]), yn(r["is_crosslink"])] for r in c]

TOTAL = len(a) + len(b) + len(c)
must(TOTAL == 699, f"三段合计 {TOTAL} 行（= 246 + 3 + 450）")

doc = f"""# Supplementary Table S4. Criterion sensitivity of the candidate ranking

<!-- Generated by 03_分析/scripts/D1_S4成表_2026-09-25.py from the frozen outputs in 02_结果表/:
     A2_名次随模型变动.csv (S4a), A2_显著性跨线计数.csv (S4b),
     A2e_留一法_逐基因名次变动.csv (S4c). No value is recomputed here; the three
     sub-tables are re-formatted only. Row counts: 246 + 3 + 450 = 699. -->

The candidate ordering set out in the main text is criterion-dependent: a gene's position depends on
which estimator is taken as primary and on which statistic the order is built from. This table reports
that dependence in three parts, all computed from the same frozen per-cohort effects as the main text.

**S4a** gives the rank of every candidate under the fixed-effect and random-effects estimators, for
both the cross-linking family and the full candidate set, and under two ordering criteria (|log2FC| and
P). **S4b** counts the candidates whose significance crosses the conventional threshold when the
estimator is switched, i.e. the cells that would change if the declared primary estimator were replaced.
**S4c** re-runs the whole ranking once per cohort deletion (leave-one-cohort-out), giving the rank of
every gene before and after each deletion and the resulting shift.

The layer labels are those of the main text: *Discovery* is the three discovery synovial cohorts,
*Replication* the three replication cohorts. Ranks are within the stated set and criterion only; they
are not comparable across sets, and no composite score is formed. A rank shift of zero does not imply
that a gene is stable in effect size, only that its position among the stated set did not move.

## S4a. Rank shifts between estimators

Ranks of each candidate under the fixed-effect (FE) and random-effects (RE) estimators, ordered by
|log2FC| or by P, within the cross-linking family (8 genes) and within the full candidate set (52 or 46
genes evaluable in that layer). `delta` is RE rank minus FE rank; a positive value means the gene falls
when the estimator is switched to random effects.

{table(["Layer", "Set", "Criterion", "Gene", "FE rank", "RE rank", "Genes in set", "delta"], rows_a)}

## S4b. Significance crossings

Number of evaluable candidates whose P value crosses 0.05 when the estimator is switched, with the
genes involved and the range of P values spanned. The first two rows compare the meta-analytic FE and
RE estimators of the same quantity; the third row is specific to the replication layer, where the
declared primary estimator is a pooled cohort-adjusted model rather than a meta-analysis, and compares
it against the random-effects version of the IVW column. The two comparisons therefore answer
different questions and are not summed.

{table(["Layer", "Comparison", "Evaluable", "Crossed", "Genes", "P min", "P max"], rows_b)}

## S4c. Per-gene leave-one-cohort-out re-ranking

For each layer and estimator, the ranking was recomputed with one cohort removed at a time. `k` is the
number of cohorts remaining, `log2FC` and `P` are the gene's values in that reduced set, `rank_abs_loo`
and `rank_P_loo` its rank in the reduced set by |log2FC| and by P, and `rank_abs_full` / `rank_P_full`
its rank in the corresponding full set. `d_abs` and `d_P` are the shifts (reduced minus full); a
negative value means the gene moves up when that cohort is removed. `In panel` marks the six genes
carried into the replication layer as the reported panel, `Cross-linking` the eight cross-linking
candidates of the curated set.

{table(["Layer", "Estimator", "Gene", "Cohort dropped", "k", "log2FC", "P", "Rank |log2FC| (LOO)",
        "Rank P (LOO)", "Rank |log2FC| (full)", "Rank P (full)", "d |log2FC|", "d P",
        "In panel", "Cross-linking"], rows_c)}

## Notes

1. **Primary estimators.** Discovery: inverse-variance-weighted fixed effect (metafor::rma, method="FE"),
   with DerSimonian-Laird random effects as its sensitivity counterpart. Replication: pooled model with
   cohort fixed effects and robust (HC3) standard errors, with the IVW fixed-effect column and its
   random-effects version as comparisons. The FE-versus-RE pairs are self-consistent within each layer;
   the replication primary-versus-RE comparison changes estimator and aggregation at once and its
   direction is not attributable to either step alone (main text §2.3).
2. **No value is recomputed in this file.** All three sub-tables are re-formatted from the same frozen
   outputs that the main text and Table 3 draw on.
3. **Reproduction.** `Rscript A2_交联家族_判据敏感性.R`, `Rscript A2e_留一法重排汇总.R`, and
   `python3 03_分析/scripts/D1_S4成表_2026-09-25.py` (this file). Inputs are the per-cohort effect
   tables from the discovery and replication layers; no resampling is involved, so these tables are
   deterministic given those inputs.
"""
cells = [x for r in rows_a + rows_b + rows_c for x in r]
bad_cells = [x for x in cells if HAN.search(x)]
must(not bad_cells, f"表格数据格无汉字（{len(cells)} 格受检）——源表的中文枚举未漏入")
bad_prose = han_in_prose(doc)
if bad_prose:
    raise SystemExit(f"✗ 正文残留汉字（非路径/文件名）：{bad_prose[:5]}")
print("  OK  正文无汉字（含汉字的 token 全部是路径或文件名）")
OUT.write_text(doc, encoding="utf-8")
print(f"\n写出 {OUT.relative_to(REV)}")
print(f"  {len(doc.splitlines())} 行 / {len(doc.encode('utf-8'))} B")
print(f"  子表：S4a {len(rows_a)} + S4b {len(rows_b)} + S4c {len(rows_c)} = {TOTAL} 行")
